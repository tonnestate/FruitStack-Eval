"""Repair order 1 (R1, R2, R3, R4, R5): the candidate ledger with a protected best, grounded-critique classification, release semantics helpers and the HOW TO RUN CHECKS block.
Everything here is decided by the host (driver-run checks), never by a model's claim, and never from hidden tests. Pure logic: the checker / runners are injected, so scripted tests need no model."""
from __future__ import annotations

import hashlib
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

TEST_LINE = re.compile(r"^(.+?) \.\.\. (ok|FAIL|ERROR|skipped.*|expected failure|unexpected success)\s*$", re.M)
MIN_QUOTE = 15                      # characters of a task-text quote that can ground an objection
MAX_VISIBLE_MODULES = 40


def sha256(diff: str) -> str:
    return hashlib.sha256((diff or "").encode()).hexdigest()


# ---- R4: checks the host can run -----------------------------------------------------------------------------------------------------------------------------
def visible_labels(tree: Path) -> list:
    """Dotted test modules of the tree (tests/<pkg>/test_*.py -> pkg.test_x). Empty for large suites: then the caller uses the labels of the candidate's own relevant run."""
    root = Path(tree) / "tests"
    mods = sorted(".".join(p.relative_to(root).with_suffix("").parts) for p in root.rglob("test*.py")) if root.is_dir() else []
    return mods if len(mods) <= MAX_VISIBLE_MODULES else []


def howto_block(python: str, labels: list) -> str:
    cmd = f"PYTHONPATH=. {python} tests/runtests.py --parallel 1 -v 2 {' '.join(labels)}"
    return ("HOW TO RUN CHECKS (generated by the host from the task configuration; copy exactly):\n"
            f"  tool call : run_tests {{\"modules\": {list(labels)!r}}}\n".replace("'", '"') +
            f"  shell     : cd <repository root of the candidate workspace> && {cmd}\n"
            "  The host also runs these checks itself on every candidate; its result is shown with the candidate.")


def parse_shell(block: str) -> str:
    """What a reviewer that reads only team_state.md would execute."""
    m = re.search(r"^\s*shell\s*:\s*cd <[^>]*>\s*&&\s*(.+)$", block, re.M)
    return m.group(1).strip() if m else ""


def tree_with_diff(base: Path, diff: str, dest: Path) -> Path:
    shutil.copytree(base, dest, ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    if (diff or "").strip():
        r = subprocess.run(["git", "apply", "--whitespace=nowarn", "-"], cwd=dest, input=diff, capture_output=True, text=True)
        if r.returncode:
            raise RuntimeError("DIFF_DOES_NOT_APPLY: " + r.stderr[-300:])
    return dest


def run_visible(python: str, tree: Path, labels: list, timeout: int = 300) -> dict:
    env = {"PYTHONWARNINGS": "ignore", "PATH": "/usr/bin:/bin", "PYTHONPATH": str(tree), "LANG": "C.UTF-8", "PYTHONDONTWRITEBYTECODE": "1"}
    argv = [python, "tests/runtests.py", "--parallel", "1", "-v", "2", *labels]
    r = subprocess.run(argv, cwd=tree, capture_output=True, text=True, timeout=timeout, env=env)
    out = r.stdout + r.stderr
    res = {m.group(1): m.group(2) in ("ok", "expected failure") for m in TEST_LINE.finditer(out)}
    return {"passed": sum(res.values()), "failed": sum(1 for v in res.values() if not v), "executed": len(res), "exit": r.returncode, "tail": out[-1500:]}


# ---- R2: which objections may force a revision ---------------------------------------------------------------------------------------------------------
def _norm(s: str) -> str:
    return re.sub(r"\s+", " ", s or "").strip()


def quotes_in(text: str) -> list:
    found = re.findall(r"\"([^\"\n]{%d,})\"|'([^'\n]{%d,})'|`([^`\n]{%d,})`" % (MIN_QUOTE, MIN_QUOTE, MIN_QUOTE), text or "")
    found = [next(x for x in t if x) for t in found]
    found += [l.lstrip("> ").strip() for l in (text or "").splitlines() if l.startswith(">") and len(l.lstrip("> ").strip()) >= MIN_QUOTE]
    return found


def classify_objection(text: str, task_text: str, check_log: list) -> dict:
    """grounded = (a) the objection reproduces, verbatim, output of a failing command that the critic ran in the sandbox (the command becomes its recorded reproduction), or
    (b) it quotes the task text verbatim (the quote must be a substring of the task text). Everything else is a suggestion."""
    for ck in reversed(check_log or []):
        if not ck.get("failing"):
            continue
        lines = [l.strip() for l in (ck.get("output") or "").splitlines() if len(l.strip()) >= 12 and not l.strip().startswith("Ran ") and not l.strip().startswith("exit=")]
        if any(l in (text or "") for l in lines):
            return {"kind": "command", "repro": {"tool": ck["tool"], "args": ck.get("args", {})}}
    task = _norm(task_text)
    for q in quotes_in(text):
        if _norm(q) and _norm(q) in task:
            return {"kind": "quote", "quote": _norm(q)}
    return {"kind": "suggestion"}


def is_grounded(ground) -> bool:
    return bool(ground) and ground.get("kind") in ("command", "quote")


# ---- R1: candidate ledger with a protected best --------------------------------------------------------------------------------------------------------
class CandidateLedger:
    """checker(diff, repros) -> {"passed": int, "failed": int, "repro": {objection_id: bool}}. Score = passes minus nothing: (passes of visible tests + recorded reproductions, -failures)."""

    def __init__(self, checker, on_write=None):
        self.checker, self.on_write = checker, on_write or (lambda kind, key, payload: None)
        self.cands, self.repros, self._cache = [], {}, {}

    def add_repro(self, oid: str, repro: dict) -> None:
        self.repros[oid] = repro

    def check(self, diff: str, repros=None) -> dict:
        reps = self.repros if repros is None else repros
        key = (sha256(diff), tuple(sorted(reps)))
        if key not in self._cache:
            self._cache[key] = self.checker(diff, reps)
        return self._cache[key]

    def score(self, diff: str) -> tuple:
        r = self.check(diff)
        rp = sum(r.get("repro", {}).values())
        rf = len(r.get("repro", {})) - rp
        return (r["passed"] + rp, -(r["failed"] + rf))

    def add(self, pos: str, label: str, diff: str, status: str = "ADOPTED", reason: str = "") -> dict:
        c = {"id": f"{pos}:{label}", "pos": pos, "label": label, "sha256": sha256(diff), "diff": diff, "seq": len(self.cands), "status": status, "reason": reason}
        c["visible"] = {k: v for k, v in self.check(diff).items() if k != "tail"} if status != "REJECTED_REVISION" else {}
        self.cands.append(c)
        self.on_write("TEAM_CANDIDATE", c["id"], {k: v for k, v in c.items() if k != "diff"} | {"diff_sha256": c["sha256"]})
        return c

    def incumbent(self, pos: str) -> dict | None:
        mine = [c for c in self.cands if c["pos"] == pos and c["status"] == "ADOPTED"]
        return mine[-1] if mine else None

    def consider_revision(self, pos: str, label: str, new_diff: str, claimed: list) -> dict:
        """claimed: ids of the GROUNDED objections the revision claims to address. Adopted only if (a) driver-run score >= the incumbent's and (b) every claimed reproduction passes."""
        inc = self.incumbent(pos)
        if inc is None:
            return {"adopted": True, "reason": "FIRST_CANDIDATE", "cand": self.add(pos, label, new_diff)}
        if not claimed:
            return {"adopted": False, "reason": "NO_GROUNDED_OBJECTION_ADDRESSED", "cand": self.add(pos, label, new_diff, "REJECTED_REVISION", "NO_GROUNDED_OBJECTION_ADDRESSED")}
        res = self.check(new_diff)
        if self.score(new_diff) < self.score(inc["diff"]):
            return {"adopted": False, "reason": "VISIBLE_SCORE_LOWER", "cand": self.add(pos, label, new_diff, "REJECTED_REVISION", "VISIBLE_SCORE_LOWER")}
        failing = [o for o in claimed if o in res.get("repro", {}) and not res["repro"][o]]
        if failing:
            reason = "REPRO_STILL_FAILING:" + ",".join(failing)
            return {"adopted": False, "reason": reason, "cand": self.add(pos, label, new_diff, "REJECTED_REVISION", reason)}
        inc["status"] = "SUPERSEDED"
        return {"adopted": True, "reason": "ADOPTED", "cand": self.add(pos, label, new_diff)}

    def best(self) -> dict | None:
        """The protected best: over EVERY adopted candidate ever accepted (superseded ones included), by driver-run score, ties -> earliest. Hidden tests are never consulted."""
        pool = [c for c in self.cands if c["status"] in ("ADOPTED", "SUPERSEDED")]
        return min(pool, key=lambda c: (tuple(-x for x in self.score(c["diff"])), c["seq"])) if pool else None


# ---- R3: release semantics -----------------------------------------------------------------------------------------------------------------------------
def release_class(unanimous: bool) -> str:
    return "RELEASED_UNANIMOUS_EXCELLENT" if unanimous else "CANDIDATE_NO_CONSENSUS"


def cites_sha(text: str, candidate_sha: str) -> bool:
    """A grounded approval cites the sha256 of exactly the final candidate (full digest or its first 12 hex characters)."""
    t = (text or "").lower()
    return candidate_sha.lower() in t or (candidate_sha[:12].lower() in t)


# ---- R5: infrastructure failure of the author ----------------------------------------------------------------------------------------------------------
def infra_author_failed(stats: dict, n_snapshots: int) -> bool:
    """Every step was a retry and nothing was accepted: the author's supply failed; that is infrastructure, never NO_PATCH."""
    steps, retries = (stats or {}).get("steps", 0), (stats or {}).get("step_retries", 0)
    return n_snapshots == 0 and steps > 0 and retries >= steps
